namespace WildEggsHatching.Core.Enums;

/// <summary>
/// Represents the different types of wild eggs.
/// </summary>
public enum EggType
{
    /// <summary>A standard wild egg found in the wild.</summary>
    wildEgg,

    /// <summary>A larger wild egg that produces more when hatched.</summary>
    largeWildEgg,

    /// <summary>A magical wild egg with enhanced properties.</summary>
    magicWildEgg,

    /// <summary>A large magical wild egg with the best properties.</summary>
    largeMagicWildEgg
}

