using System.Text;

// args:
//   --projectDir <dir>
//   --fileList   <path to txt with one file path per line, relative to projectDir>
//   --out        <output .cs path>
//   --ns         <namespace>
//   --class      <class name> (optional, default EmbeddedTextFiles)
var parsed = ParseArgs(args);

var projectDir = Require(parsed, "--projectDir");
var fileList = Require(parsed, "--fileList");
var outPath = Require(parsed, "--out");
var ns = Require(parsed, "--ns");
var className = parsed.TryGetValue("--class", out var c) ? c : "EmbeddedTextFiles";

var relFiles = File.ReadAllLines(fileList, Encoding.UTF8)
    .Select(l => l.Trim())
    .Where(l => !string.IsNullOrWhiteSpace(l))
    .Select(NormalizeRel)
    .Distinct(StringComparer.OrdinalIgnoreCase)
    .ToList();

Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated />");
sb.AppendLine("namespace " + ns + ";");
sb.AppendLine();
sb.AppendLine("using System;");
sb.AppendLine("using System.Collections.Generic;");
sb.AppendLine();
sb.AppendLine($"internal static class {className}");
sb.AppendLine("{");
sb.AppendLine("    internal static readonly IReadOnlyDictionary<string, string> Files =");
sb.AppendLine("        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)");
sb.AppendLine("        {");

foreach (var rel in relFiles)
{
    var abs = Path.Combine(projectDir, rel.Replace('/', Path.DirectorySeparatorChar));
    if (!File.Exists(abs))
        throw new FileNotFoundException($"Missing file to embed: {abs}");

    var text = File.ReadAllText(abs, Encoding.UTF8);

    sb.Append("            [\"");
    sb.Append(rel.Replace("\"", "\\\""));
    sb.Append("\"] = @\"");
    sb.Append(text.Replace("\"", "\"\""));
    sb.AppendLine("\",");
}

sb.AppendLine("        };");
sb.AppendLine("}");
File.WriteAllText(outPath, sb.ToString(), Encoding.UTF8);

static Dictionary<string, string> ParseArgs(string[] a)
{
    var d = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
    for (var i = 0; i < a.Length; i++)
    {
        var k = a[i];
        if (!k.StartsWith("--", StringComparison.Ordinal))
            continue;

        var v = (i + 1 < a.Length && !a[i + 1].StartsWith("--", StringComparison.Ordinal)) ? a[++i] : "true";
        d[k] = v;
    }

    return d;
}

static string Require(Dictionary<string, string> d, string key)
    => d.TryGetValue(key, out var v) ? v : throw new ArgumentException($"Missing arg {key}");

static string NormalizeRel(string path)
    => path.Replace('\\', '/').TrimStart('/');
