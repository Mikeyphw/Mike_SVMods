#!/usr/bin/env python3
"""Source-only R7 workflow inventory: reject graph or evidence-gate elision."""
from __future__ import annotations
import re
import sys
from pathlib import Path

R7 = '.github/workflows/devtool-dn03-r7-native-ci.yml'
BASE_R6 = '.github/workflows/devtool-dn03r4-dn03_r5-native_r6.yml'
PIN = '0ebd22c17ac3058704012a1e03ee3265328b0659'


def check(root: Path) -> None:
    path = root / R7
    assert path.is_file() and not path.is_symlink()
    s = path.read_text(encoding='utf-8')
    assert s.startswith('# Generated by Devtool RM-06:')
    assert '  pull_request:\n    branches: [main]' in s
    assert '  push:\n    branches: [main]' in s
    assert '  workflow_dispatch:' in s
    assert PIN in s
    assert s.count('DN03_R7_29_OF_29_TYPED_TRX_GATE_PASS') == 1
    assert s.count('DN03_R7_SOURCE_GRAPH_ADMITTED=') == 1
    assert s.count('needs.r7_plan.outputs.graph_sha') >= 8
    jobs=re.findall(r'^  ([A-Za-z0-9_-]+):$',s.split('jobs:\n', 1)[1],flags=re.M)
    assert jobs == ['r7_plan']+[f'node-{i:02}' for i in range(1,7)]+['dn03_r4_acceptance']
    for i in range(1,7):
        assert s.count(f'  node-{i:02}:\n') == 1
    assert '      - name: R7 fail-closed 29-test acceptance gate' in s
    assert "assert a['verified_test_case_count'] == 29" in s
    assert "assert a['verified_test_node_count'] == 2" in s
    assert 'assert a[\'remote_authenticated\'] is False and a[\'release_qualified\'] is False' in s
    assert 'DN03_R4_NEEDS_JSON=' in s
    assert (root/BASE_R6).is_file() and not (root/BASE_R6).is_symlink()
    assert len(s.encode('utf-8')) < 112_000


if __name__ == '__main__':
    check(Path(sys.argv[1]).resolve() if len(sys.argv)>1 else Path.cwd())
    print('DN03_R7_GATE_SOURCE_CONTRACT_PASS')
